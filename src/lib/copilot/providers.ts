import { estimateCostUsd, ratesFromEnv, type RateCard } from "@/lib/copilot/cost";
import {
  selectModel,
  type ProviderId,
  type TaskSize,
} from "@/lib/copilot/models";

export type CompletionRequest = {
  system: string;
  user: string;
  maxTokens?: number;
};

export type CompletionResult = {
  text: string;
  provider: ProviderId;
  model: string;
  promptTokens: number;
  completionTokens: number;
  estimatedCostUsd: number;
};

export interface CopilotProvider {
  id: ProviderId;
  model: string;
  task: TaskSize;
  complete(request: CompletionRequest): Promise<CompletionResult>;
}

export class ProviderNotConfiguredError extends Error {
  constructor() {
    super("XAI_API_KEY is required in production");
    this.name = "ProviderNotConfiguredError";
  }
}

type ChatResponse = {
  choices?: Array<{ message?: { content?: string } }>;
  usage?: { prompt_tokens?: number; completion_tokens?: number };
};

async function completeChat(args: {
  url: string;
  apiKey: string;
  model: string;
  provider: "xai";
  task: TaskSize;
  request: CompletionRequest;
  rates: RateCard;
  timeoutMs: number;
}): Promise<CompletionResult> {
  const response = await fetch(args.url, {
    method: "POST",
    headers: {
      authorization: `Bearer ${args.apiKey}`,
      "content-type": "application/json",
    },
    body: JSON.stringify({
      model: args.model,
      messages: [
        { role: "system", content: args.request.system },
        { role: "user", content: args.request.user },
      ],
      ...(args.request.maxTokens ? { max_tokens: args.request.maxTokens } : {}),
    }),
    signal: AbortSignal.timeout(args.timeoutMs),
  });
  if (!response.ok) {
    const detail = (await response.text()).replace(/\s+/g, " ").trim().slice(0, 180);
    throw new Error(
      `${args.provider} request failed (${response.status}) for model ${args.model}${detail ? `: ${detail}` : ""}`,
    );
  }
  const json = (await response.json()) as ChatResponse;
  const text = json.choices?.[0]?.message?.content ?? "";
  const promptTokens =
    json.usage?.prompt_tokens ??
    Math.ceil((args.request.system.length + args.request.user.length) / 4);
  const completionTokens =
    json.usage?.completion_tokens ?? Math.ceil(text.length / 4);
  return {
    text,
    provider: args.provider,
    model: args.model,
    promptTokens,
    completionTokens,
    estimatedCostUsd: estimateCostUsd(
      { prompt: promptTokens, completion: completionTokens },
      args.rates,
    ),
  };
}

export function createFakeProvider(task: TaskSize, model: string): CopilotProvider {
  return {
    id: "fake",
    model,
    task,
    async complete(request) {
      const wantsJson = request.system.includes("JSON shape");
      const rawSlug = /^Page slug: (.*)$/m.exec(request.user)?.[1]?.trim() ?? "";
      const slug = rawSlug === "(home)" ? "" : rawSlug;
      const title = /^Page title: (.*)$/m.exec(request.user)?.[1]?.trim();
      const text = wantsJson
        ? JSON.stringify({
            pages: [
              {
                slug,
                section: slug ? "Guides" : "Start",
                title: title || "Local preview",
                description: "Generated by the local fake provider.",
                navOrder: 0,
                content:
                  "This page was generated by the local fake provider.\n\nAdd an API key to use a real model.",
              },
            ],
            removedSlugs: [],
            changeNote: "Local fake build",
          })
        : `Fake ${task} completion.\n\n${request.user.slice(0, 240)}`;
      return {
        text,
        provider: "fake",
        model,
        promptTokens: Math.max(1, Math.ceil(request.user.length / 4)),
        completionTokens: Math.max(1, Math.ceil(text.length / 4)),
        estimatedCostUsd: 0,
      };
    },
  };
}

export function createXaiProvider(
  model: string,
  apiKey: string,
  env: Record<string, string | undefined>,
  task: TaskSize = "heavy",
): CopilotProvider {
  return {
    id: "xai",
    model,
    task,
    complete(request) {
      return completeChat({
        url: "https://api.x.ai/v1/chat/completions",
        apiKey,
        model,
        provider: "xai",
        task,
        request,
        rates: ratesFromEnv(env),
        timeoutMs: 120_000,
      });
    },
  };
}

export function resolveProvider(
  task: TaskSize,
  env: Record<string, string | undefined> = process.env,
): CopilotProvider {
  const choice = selectModel(task, env);
  const production = env.NODE_ENV === "production";
  const forceFake = env.COPILOT_PROVIDER === "fake";
  if (choice.provider === "xai") {
    if (env.XAI_API_KEY && !forceFake) {
      return createXaiProvider(choice.model, env.XAI_API_KEY, env, task);
    }
    if (production && !forceFake) throw new ProviderNotConfiguredError();
    return createFakeProvider(task, choice.model);
  }
  return createFakeProvider(task, choice.model);
}
